"""Post-generation Terraform tag checker (MA-402).

After Bandit/tfsec/Checkov scan, this module adds an additional local
check that verifies every Azure ``resource`` block in a generated
Terraform artifact carries the three mandatory tags
(``environment``, ``owner``, ``cost_center``).

The check is intentionally conservative — it uses regex, not a full HCL
parser, so it flags *potentially* missing tags rather than silently
passing ambiguous code.  This gives a CRITICAL finding that blocks
the approval flow until the Coder addresses the gap.
"""

from __future__ import annotations

import re

from src.agents.coder_agent import REQUIRED_AZURE_TAGS
from src.workflow.models import (
    ArtifactLanguage,
    FindingSeverity,
    GeneratedArtifact,
    ScanReport,
    SecurityFinding,
)

# Match the opening of a Terraform azurerm resource block.
# Groups: (resource_type, resource_name)
_AZURERM_RESOURCE_OPEN_RE = re.compile(
    r'resource\s+"(azurerm_[^"]+)"\s+"([^"]+)"\s*\{',
)

# Match a tags block inside a resource body.
_TAGS_BLOCK_RE = re.compile(r'\btags\s*=\s*\{([^}]*)\}', re.DOTALL)

# Match a single tag key inside a tags block.
_TAG_KEY_RE = re.compile(r'^\s*(\w+)\s*=', re.MULTILINE)

TOOL_NAME = "tag-policy"


def _extract_resource_bodies(content: str) -> list[tuple[str, str, str]]:
    """Return (resource_type, resource_name, body) for every azurerm resource block.

    Uses a brace counter to correctly handle nested blocks (tags = {}, dynamic {}, etc.)
    without relying on a greedy regex that fails on multi-line sub-blocks.
    """
    results = []
    for match in _AZURERM_RESOURCE_OPEN_RE.finditer(content):
        resource_type = match.group(1)
        resource_name = match.group(2)
        start = match.end()  # position just after the opening '{'
        depth = 1
        pos = start
        while pos < len(content) and depth > 0:
            if content[pos] == '{':
                depth += 1
            elif content[pos] == '}':
                depth -= 1
            pos += 1
        body = content[start : pos - 1]  # everything between outer braces
        results.append((resource_type, resource_name, body))
    return results


def check_required_tags(artifact: GeneratedArtifact) -> ScanReport:
    """Return a :class:`~src.workflow.models.ScanReport` for missing tags.

    Only Terraform artifacts are checked; Python artifacts receive a
    pass-through report with zero findings.

    Parameters
    ----------
    artifact:
        The artifact generated by the Coder agent.

    Returns
    -------
    ScanReport
        A report with one CRITICAL :class:`~src.workflow.models.SecurityFinding`
        per resource that is missing one or more required tags.
    """
    if artifact.language is not ArtifactLanguage.TERRAFORM:
        return ScanReport(tool=TOOL_NAME, succeeded=True, findings=())

    findings: list[SecurityFinding] = []
    for resource_type, resource_name, body in _extract_resource_bodies(artifact.content):
        present_tags = _extract_tag_keys(body)
        missing = [tag for tag in REQUIRED_AZURE_TAGS if tag not in present_tags]
        if missing:
            findings.append(
                SecurityFinding(
                    tool=TOOL_NAME,
                    rule_id="MA-402-MISSING-TAGS",
                    severity=FindingSeverity.CRITICAL,
                    message=(
                        f'Resource "{resource_type}" "{resource_name}" is missing required '
                        f"tags: {', '.join(missing)}."
                    ),
                    remediation=(
                        "Add a tags block to the resource containing all of: "
                        + ", ".join(REQUIRED_AZURE_TAGS)
                        + ".  See the Coder system prompt for the required format."
                    ),
                    location=artifact.filename,
                )
            )

    return ScanReport(tool=TOOL_NAME, succeeded=True, findings=tuple(findings))


def _extract_tag_keys(resource_body: str) -> set[str]:
    """Return the set of tag key names found inside the resource body."""
    tags_match = _TAGS_BLOCK_RE.search(resource_body)
    if tags_match is None:
        return set()
    return {m.group(1) for m in _TAG_KEY_RE.finditer(tags_match.group(1))}
